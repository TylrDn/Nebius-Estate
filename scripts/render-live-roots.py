def fmt(files: dict[str, str]) -> dict[str, str]:
    """Run `terraform fmt` over the rendered .tf/.hcl files so the output is byte-stable."""
    if shutil.which("terraform") is None:
        return files
    with tempfile.TemporaryDirectory() as tmp:
        for rel, content in files.items():
            p = Path(tmp) / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content)
        subprocess.run(["terraform", "fmt", "-recursive", tmp], check=True, capture_output=True)
        return {rel: (Path(tmp) / rel).read_text() for rel in files}


def main() -> int:
    if sys.argv[1:2] == ["--policy"]:  # --policy <stage> <key>: print one policy value (the pipeline gate reads it)
        stage, key = sys.argv[2], sys.argv[3]
        print(dict(stage_policies()[stage])[key])
        return 0
    check = "--check" in sys.argv
    stale: list[str] = []
    for stage in stages():
        only = stage_stacks(stage)
        for stack in STACKS:
            d = ROOT / "terraform" / "live" / stage / stack
            if only is not None and stack not in only:
                if d.exists():
                    stale.append(f"{d.relative_to(ROOT)} ({stack} is not in stages.{stage}.stacks: remove this root)")
                continue
            if stack in GPU_GATED and gpu_cap(stage, stack) == 0:
                if d.exists():
                    stale.append(f"{d.relative_to(ROOT)} (max_gpu_nodes.{stack} is 0 in {stage}: remove this root)")
                continue
            files = fmt(render_stack_root(stage, stack))
            # Same providers as the stack, so the stack's lock file is the live root's lock file
            # (init runs -lockfile=readonly everywhere).
            files[".terraform.lock.hcl"] = (ROOT / "terraform" / "stacks" / stack / ".terraform.lock.hcl").read_text()
            for rel, content in files.items():
                p = d / rel
                if check:
                    if not p.exists() or p.read_text() != content:
                        stale.append(str(p.relative_to(ROOT)))
                    continue
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(content)
            tfvars = d / f"{stage}.auto.tfvars"
            if not tfvars.exists() and not check:
                tfvars.write_text(f"# Sizing for stage {stage} (hand-maintained; the stage policy is in platform/stages.yaml).\n# parent_id, region and iam_token come from scripts/bootstrap-backend.sh {stage} {stack}.\n")
        d = ROOT / "terraform" / "live" / stage / "soperator"
        if only is not None and "soperator" not in only:
            if d.exists():
                stale.append(f"{d.relative_to(ROOT)} (soperator is not in stages.{stage}.stacks: remove this root)")
            continue
        for rel, content in render_soperator(stage).items():
            p = d / rel
            if check:
                if not p.exists() or p.read_text() != content:
                    stale.append(str(p.relative_to(ROOT)))
                continue
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content)
        tfvars = d / "stage.tfvars"
        if not tfvars.exists() and not check:
            tfvars.write_text(SOPERATOR_STAGE_DEFAULTS.get(stage, f'# Stage overrides applied after profiles/lab.tfvars (last -var-file wins). Hand-maintained.\ncompany_name = "nip-{stage}"\n'))
    readme = render_platform_readme()
    if readme is None:
        stale.append(f"{PLATFORM_README.relative_to(ROOT)} (stage-policy markers missing)")
    elif PLATFORM_README.read_text() != readme:
        if check:
            stale.append(str(PLATFORM_README.relative_to(ROOT)))
        else:
            PLATFORM_README.write_text(readme)
    if check:
        if stale:
            print("stale generated live roots (run make render-live):\n  " + "\n  ".join(stale))
            return 1
        print("live roots are up to date")
        return 0
    if stale:
        print("cannot render:\n  " + "\n  ".join(stale))
        return 1
    print(f"rendered live roots for stages {', '.join(stages())} and the stage-policy table")
    return 0


if __name__ == "__main__":
    sys.exit(main())
