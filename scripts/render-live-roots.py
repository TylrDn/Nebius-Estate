#!/usr/bin/env python3
"""Render terraform/live/<stage>/<stack>/ roots from platform/stages.yaml and the stacks.

A live root is a thin wrapper (ADR-0009): backend, providers, the stack's provider lock, one module call into
terraform/stacks/<stack>, pass-through variables and outputs, and a mocked plan test that pins
the stage. Hand-maintained files in a live root are never overwritten: <stage>.auto.tfvars
(sizing) and README.md are created only when absent. Everything else is generated and CI fails
when it is stale (`make render-live && git diff --exit-code terraform/live`).

It also renders the per-stage policy table in platform/README.md (between the stage-policy
markers) from the same file, so no document hand-copies a policy value.

Usage: scripts/render-live-roots.py [--check]
       scripts/render-live-roots.py --policy <stage> <key>   (print one policy value; used by terraform.yml)
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STAGES_FILE = ROOT / "platform" / "stages.yaml"
STACKS = ["network", "data", "inference", "training", "gpu-vm", "ml-services", "governance", "nvl"]  # soperator wraps the upstream recipe: see render_soperator()
# Stacks that always plan GPUs (no zero-GPU mode): a stage whose max_gpu_nodes gives them 0 gets no
# live root at all, so there is nothing to dispatch (prod has no R10 GPU VM; no stage has an R15 NVL
# rack until a GB300 reservation is approved and max_gpu_nodes.nvl is raised).
GPU_GATED = {"gpu-vm", "nvl"}
PLATFORM_README = ROOT / "platform" / "README.md"
POLICY_BEGIN = "<!-- BEGIN GENERATED stage-policy: scripts/render-live-roots.py from platform/stages.yaml; do not edit -->"
POLICY_END = "<!-- END GENERATED stage-policy -->"
GENERATED = "# GENERATED by scripts/render-live-roots.py from platform/stages.yaml and terraform/stacks/{stack}; do not edit.\n"


def stages() -> list[str]:
    names, in_stages = [], False
    for line in STAGES_FILE.read_text().splitlines():
        if line.startswith("stages:"):
            in_stages = True
            continue
        if in_stages and re.match(r"^\S", line):
            break
        m = re.match(r"^  (\w+):\s*$", line)
        if in_stages and m:
            names.append(m.group(1))
    return names


def stage_policies() -> dict[str, list[tuple[str, str]]]:
    """Return {stage: [(key, value)]} from the policy block of each stage (values as written)."""
    out: dict[str, list[tuple[str, str]]] = {}
    stage, in_policy = None, False
    for line in STAGES_FILE.read_text().splitlines():
        if re.match(r"^\S", line):
            stage, in_policy = None, False
            continue
        m = re.match(r"^  (\w+):\s*$", line)
        if m:
            stage, in_policy = m.group(1), False
            out[stage] = []
            continue
        if stage and re.match(r"^    policy:\s*$", line):
            in_policy = True
            continue
        if stage and re.match(r"^    \w", line):
            in_policy = False
            continue
        m = re.match(r"^      (\w+):\s*(.*?)\s*(#.*)?$", line)
        if stage and in_policy and m:
            out[stage].append((m.group(1), m.group(2)))
    return out


def stage_stacks(stage: str) -> list[str] | None:
    """The stage's `stacks:` list (only these live roots are rendered), or None when it has none (every stack)."""
    m = re.search(rf"^  {re.escape(stage)}:\n(?:    .*\n|\s*\n)*?    stacks:\s*\[([^\]]*)\]", STAGES_FILE.read_text(), re.M)
    return [x.strip() for x in m.group(1).split(",") if x.strip()] if m else None


def gpu_cap(stage: str, stack: str) -> int:
    """max_gpu_nodes[stack] for the stage (0 when the stage does not list the stack)."""
    raw = dict(stage_policies()[stage]).get("max_gpu_nodes", "{}")
    caps = dict((k.strip(), v.strip()) for k, v in (kv.split(":") for kv in raw.strip("{} ").split(",") if ":" in kv))
    return int(caps.get(stack, "0"))


def render_policy_table() -> str:
    pol = stage_policies()
    names = list(pol)
    keys = [k for k, _ in pol[names[0]]]

    def word(v: str) -> str:
        return {"true": "yes", "false": "no"}.get(v.strip(), v.strip())

    def cell(v: str) -> str:
        m = re.match(r"^\{(.*)\}$", v)
        if m:
            return " · ".join(f"{a.strip()} {word(b)}" for a, b in (kv.split(":") for kv in m.group(1).split(",")))
        return word(v)

    rows = ["| Policy (`platform/stages.yaml`) | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    for k in keys:
        rows.append(f"| `{k}` | " + " | ".join(cell(dict(pol[n]).get(k, "")) for n in names) + " |")
    return POLICY_BEGIN + "\n" + "\n".join(rows) + "\n" + POLICY_END


def render_platform_readme() -> str | None:
    text = PLATFORM_README.read_text()
    if POLICY_BEGIN not in text or POLICY_END not in text:
        return None
    head, rest = text.split(POLICY_BEGIN, 1)
    _, tail = rest.split(POLICY_END, 1)
    return head + render_policy_table() + tail


def parse_variables(path: Path) -> list[dict]:
    """Return [{name, description, type, default}] for every variable block (validations dropped:
    they run in the stack, and their relative paths only resolve from the stack's depth)."""
    text = path.read_text()
    out = []
    for m in re.finditer(r'^variable "([^"]+)" \{\n', text, re.M):
        name, i, depth = m.group(1), m.end(), 1
        while depth:
            c = text[i]
            depth += {"{": 1, "}": -1}.get(c, 0)
            i += 1
        body = text[m.end() : i - 1]
        var = {"name": name, "description": None, "type": None, "default": None, "sensitive": "sensitive   = true" in body or "sensitive = true" in body, "ephemeral": bool(re.search(r"^\s*ephemeral\s*=\s*true", body, re.M))}
        for key in ("description", "type", "default"):
            km = re.search(rf"^\s*{key}\s*=\s*", body, re.M)
            if not km:
                continue
            j, d = km.end(), 0
            while j < len(body):
                ch = body[j]
                d += {"{": 1, "[": 1, "(": 1, "}": -1, "]": -1, ")": -1}.get(ch, 0)
                if ch == "\n" and d == 0:
                    break
                j += 1
            var[key] = body[km.end() : j].strip()
        out.append(var)
    return out


def parse_outputs(path: Path) -> list[tuple[str, str | None, bool]]:
    text = path.read_text()
    res = []
    for m in re.finditer(r'^output "([^"]+)" \{\n(.*?)^\}\n', text, re.M | re.S):
        body = m.group(2)
        dm = re.search(r'description\s*=\s*"((?:[^"\\]|\\.)*)"', body)
        res.append((m.group(1), dm.group(1) if dm else None, "sensitive" in body))
    return res


def render_stack_root(stage: str, stack: str) -> dict[str, str]:
    stack_dir = ROOT / "terraform" / "stacks" / stack
    variables = [v for v in parse_variables(stack_dir / "variables.tf") if v["name"] != "stage"]
    outputs = parse_outputs(stack_dir / "outputs.tf")
    g = GENERATED.format(stack=stack)
    files: dict[str, str] = {}

    files["versions.tf"] = g + (stack_dir / "versions.tf").read_text()

    files["backend.tf"] = g + f'''# Remote state in Nebius Object Storage (S3-compatible). Bucket, key, endpoint and region
# come from the git-ignored backend.hcl written by `scripts/bootstrap-backend.sh {stage} {stack}`
# (state key stages/{stage}/{stack}.tfstate, bucket per stage, ADR-0005 / ADR-0009):
#   terraform -chdir=terraform/live/{stage}/{stack} init -reconfigure -backend-config=backend.hcl
terraform {{
  backend "s3" {{
    skip_region_validation      = true
    skip_credentials_validation = true
    skip_requesting_account_id  = true
    skip_s3_checksum            = true
    skip_metadata_api_check     = true
    use_lockfile                = true
  }}
}}
'''

    nebius_provider = '''# Authentication: an IAM token from `nebius iam get-access-token`, exported as TF_VAR_iam_token
# by scripts/bootstrap-backend.sh (user tokens are for local use; the service-account block is
# the CI path, see terraform/README.md).
provider "nebius" {
  token     = var.iam_token
  parent_id = var.parent_id
}
'''
    # Stacks without a cluster (network, data) declare only the nebius provider.
    if "hashicorp/helm" not in (stack_dir / "versions.tf").read_text():
        files["providers.tf"] = g + nebius_provider
    else:
        files["providers.tf"] = g + nebius_provider + '''
# The Kubernetes-side providers read the stack's outputs so one apply creates the cluster and
# installs the platform layer (ADR-0006).
provider "helm" {
  kubernetes = {
    host                   = module.stack.k8s_host
    cluster_ca_certificate = module.stack.cluster_ca_certificate
    token                  = var.iam_token
  }
}

provider "kubernetes" {
  host                   = module.stack.k8s_host
  cluster_ca_certificate = module.stack.cluster_ca_certificate
  token                  = var.iam_token
}

provider "kubectl" {
  apply_retry_count      = 5
  host                   = module.stack.k8s_host
  cluster_ca_certificate = module.stack.cluster_ca_certificate
  token                  = var.iam_token
  load_config_file       = false
}
'''

    args = "\n".join(f"  {v['name']:<{max(len(x['name']) for x in variables)}} = var.{v['name']}" for v in variables)
    files["main.tf"] = g + f'''# Stage "{stage}" of the {stack} stack (ADR-0009). Sizing lives in {stage}.auto.tfvars; the
# policy for this stage (etcd, endpoint exposure, GPU caps, TTL labels) is enforced inside the
# stack from platform/stages.yaml, so promoting means applying this same module elsewhere.
module "stack" {{
  source = "../../../stacks/{stack}"

  stage = "{stage}"
{args}
}}
'''

    vblocks = []
    for v in variables:
        lines = [f'variable "{v["name"]}" {{']
        if v["description"]:
            lines.append(f'  description = {v["description"]}')
        if v["type"]:
            lines.append(f'  type        = {v["type"]}')
        if v["default"] is not None:
            lines.append(f'  default     = {v["default"]}')
        if v["sensitive"]:
            lines.append("  sensitive   = true")
        if v["ephemeral"]:
            lines.append("  ephemeral   = true")
        lines.append("}")
        vblocks.append("\n".join(lines))
    token_block = """# The providers' credential lives in the live root, not the stack (the stack is provider-agnostic).
# ephemeral: the token is used during the run and never written to the plan file or the state
# (Terraform >= 1.10), so a saved plan no longer carries a 12-hour credential.
variable "iam_token" {
  description = "Nebius IAM token for the nebius/helm/kubernetes providers: a user login locally (scripts/bootstrap-backend.sh) or the stage's service account in CI (scripts/ci-token.sh), both exported as TF_VAR_iam_token."
  type        = string
  sensitive   = true
  ephemeral   = true
}"""
    files["variables.tf"] = g + "# Pass-through of the stack's inputs (validations run in the stack).\n\n" + "\n\n".join([token_block, *vblocks]) + "\n"

    oblocks = []
    for name, desc, sensitive in outputs:
        lines = [f'output "{name}" {{']
        if desc:
            lines.append(f'  description = "{desc}"')
        if sensitive:
            lines.append("  sensitive   = true")
        lines.append(f"  value       = module.stack.{name}")
        lines.append("}")
        oblocks.append("\n".join(lines))
    files["outputs.tf"] = g + "\n\n".join(oblocks) + "\n"

    mocks = (stack_dir / "tests" / sorted(p.name for p in (stack_dir / "tests").glob("*.tftest.hcl"))[0]).read_text()
    mock_block = mocks[: mocks.index("variables {")]
    # A stack test may stub the shared stage policy (override_module); a live root runs the real one.
    stripped = re.sub(r"^override_module \{\n.*?^\}\n\n?", "", mock_block, flags=re.M | re.S)
    if stripped != mock_block:  # the stack test's header describes the stub: say what runs here instead
        stripped = "# Mocks from the stack's tests; the real modules/stage-policy runs here.\n\n" + stripped[stripped.index("mock_provider"):]
    mock_block = stripped
    # The real allowlist is the operator's egress, passed at plan time (never committed); the test
    # supplies a private range so stages that require one still plan.
    cidrs = '  allowed_cidrs = ["10.10.0.0/16"] # test-only; real values come from TF_VAR_allowed_cidrs\n' if any(v["name"] == "allowed_cidrs" for v in parse_variables(stack_dir / "variables.tf")) else ""
    stack_vars = {v["name"] for v in parse_variables(stack_dir / "variables.tf")}
    # The subnet comes from bootstrap-backend.sh (TF_VAR_subnet_id) or R7; subnet_name has no default.
    subnet = '  subnet_id = "vpcsubnet-e00mock0000000000" # test-only; real values come from TF_VAR_subnet_id\n' if "subnet_id" in stack_vars else ""
    # R10's login key is required and has no default; the real one comes from TF_VAR_ssh_public_key.
    ssh = '  ssh_public_key = "ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIMockKeyForPlanTestsOnly0000000000000000" # test-only\n' if "ssh_public_key" in stack_vars else ""
    # R15 joins an existing cluster (R3's cluster_id); the real one comes from TF_VAR_cluster_id.
    cluster = '  cluster_id = "mk8scluster-e00mock0000000" # test-only; real values come from TF_VAR_cluster_id\n' if "cluster_id" in stack_vars else ""
    # Cluster, node group and filesystem names are fixed at creation: pin the name each stage's
    # tfvars (or the stage-derived default) produces, so a rename never slips into a plan unnoticed.
    name_check = f'''

  assert {{
    condition     = output.cluster_name == "nip-{stage}-{stack}"
    error_message = "the cluster name must stay nip-{stage}-{stack} (docs/naming.md); a rename replaces the cluster"
  }}''' if "cluster_name" in stack_vars else ""
    files["tests/stage.tftest.hcl"] = g + mock_block + f'''variables {{
{cidrs}{subnet}{ssh}{cluster}  iam_token = "mock-token"
  parent_id = "project-e00mock"
  region    = "eu-north1"
  labels = {{
    "nip-env"         = "{stack}"
    "nip-owner"       = "ci"
    "nip-run"         = "mock"
    "nip-ttl-expires" = timeadd(timestamp(), "24h") # inside the 7-day sandbox window
  }}
}}

run "{stage}_root_plans_with_its_stage_policy" {{
  command = plan

  assert {{
    condition     = output.stage == "{stage}"
    error_message = "the live root must pin stage = {stage}"
  }}{name_check}
}}
'''
    return files


def render_soperator(stage: str) -> dict[str, str]:
    g = GENERATED.format(stack="soperator")
    # prod sets production = true, which makes the recipe require iam_merge_request_url; the
    # recipe's own terraform.tfvars sets it to "" and a var file beats TF_VAR_*, so only -var works.
    prod_var = " \\\n  -var iam_merge_request_url='https://<your-git-host>/.../merge_requests/<id>'" if stage == "prod" else ""
    prod_note = (
        "\n`production = true` makes the recipe require `iam_merge_request_url`; pass it with `-var` as above"
        "\n(the recipe's `terraform.tfvars` sets it to an empty string, which beats `TF_VAR_*`)."
        if stage == "prod" else ""
    )
    return {
        "README.generated.md": g.replace("# GENERATED", "<!-- GENERATED").replace("do not edit.", "do not edit. -->") + f'''# Soperator, stage `{stage}`

The Soperator stack wraps the upstream recipe (`terraform/stacks/soperator`), so this directory
holds only this stage's tfvars layer and its backend config:

```bash
source scripts/bootstrap-backend.sh {stage} soperator     # bucket per stage, key stages/{stage}/soperator.tfstate
scripts/fetch-soperator.sh --stage {stage}                # recipe at the pinned tag + overrides + backend override
cd terraform/stacks/soperator/upstream/soperator/installations/example
terraform plan -var-file=terraform.tfvars \\
  -var-file=../../../../profiles/lab.tfvars \\
  -var-file=../../../../../../live/{stage}/soperator/stage.tfvars{prod_var} -out=soperator-{stage}.tfplan
```

Var files apply in order: the recipe example, the lab profile, then `stage.tfvars` (last wins).{prod_note}
The mocked plan in CI runs the same three files for every stage.
''',
    }


