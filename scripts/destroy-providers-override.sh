#!/usr/bin/env bash
# Pin the Kubernetes-side providers of a live root to the cluster in its state before a destroy
# plan (runbooks/teardown.md, docs/upstream-findings.md 2026-10-11).
#
# In a destroy plan Terraform treats the cluster as going away, so module.stack.k8s_host and
# cluster_ca_certificate evaluate to null and the helm/kubernetes/kubectl providers fall back to
# http://localhost: refreshing any in-cluster resource (helm_release, kubernetes_*, kubectl_*)
# fails with "connection refused". This script reads `terraform show -json` (the root's current
# state) and, when the state holds a Managed Kubernetes cluster AND any helm/kubernetes/kubectl
# resource, writes the git-ignored zz_destroy_override.tf (mode 600) whose provider blocks carry
# the endpoint and CA inline (override files cannot add locals). The token stays var.iam_token.
# Otherwise it writes nothing and removes a stale file it wrote earlier.
#
# Endpoint: the one the stack used. The state's public_endpoint_enabled output decides; without
# it, the public endpoint when present, else the private one (reachable only from inside the
# cluster's VPC: a bastion or the self-hosted runner).
#
#   scripts/destroy-providers-override.sh <stage> <stack>        (terraform/live/<stage>/<stack>)
#   scripts/destroy-providers-override.sh --dir <terraform-root>
#   ... --remove     delete the file this script wrote (make destroy runs it after success)
# Needs: terraform (TERRAFORM overrides), jq. Read-only towards the cloud and the state.
set -euo pipefail
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
name="zz_destroy_override.tf"
marker="# GENERATED by scripts/destroy-providers-override.sh for a destroy plan; delete after the destroy."
dir=""; remove=0; pos=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --dir) dir="${2:?--dir needs a value}"; shift 2 ;;
    --remove) remove=1; shift ;;
    -h|--help) sed -n '2,21p' "$0"; exit 0 ;;
    -*) echo "unknown argument: $1" >&2; exit 2 ;;
    *) pos+=("$1"); shift ;;
  esac
done
if [[ -z "${dir}" ]]; then
  (( ${#pos[@]} == 2 )) || { echo "usage: $0 <stage> <stack> | --dir <terraform-root> [--remove]" >&2; exit 2; }
  if [[ "${pos[0]}" == foundation ]]; then dir="${repo_root}/terraform/live/foundation"; else dir="${repo_root}/terraform/live/${pos[0]}/${pos[1]}"; fi
fi
[[ -d "${dir}" ]] || { echo "no such terraform root: ${dir}" >&2; exit 2; }
out="${dir}/${name}"

# Only ever delete a file this script wrote (a hand-written override with this name is kept).
remove_ours() {
  [[ -f "${out}" ]] || return 0
  if head -n 1 "${out}" | grep -qxF "${marker}"; then rm -f "${out}"; echo "removed ${out}"
  else echo "kept ${out}: not written by $(basename "$0"); remove it by hand" >&2; fi
}
if (( remove )); then remove_ours; exit 0; fi

tf="${TERRAFORM:-terraform}"
for c in "${tf}" jq; do command -v "$c" >/dev/null || { echo "missing: $c" >&2; exit 2; }; done
state_json="$("${tf}" -chdir="${dir}" show -json)" || { echo "terraform show -json failed in ${dir} (run make init first)" >&2; exit 1; }

# Every resource in every module (data sources too: they are read during the plan's refresh).
facts="$(jq -c '
  def one: if type == "array" then .[0] else . end;
  [.values.root_module? // {} | recurse(.child_modules[]?) | .resources[]?] as $r
  | ($r | map(select(.mode == "managed" and .type == "nebius_mk8s_v1_cluster"))) as $c
  | {
      clusters: ($c | length),
      k8s: ([$r[] | select(.type | test("^(helm|kubernetes|kubectl)_")) | .address] | length),
      public: ($c[0].values.status | one | .control_plane? | one | .endpoints? | one | .public_endpoint? // ""),
      private: ($c[0].values.status | one | .control_plane? | one | .endpoints? | one | .private_endpoint? // ""),
      ca: ($c[0].values.status | one | .control_plane? | one | .auth? | one | .cluster_ca_certificate? // ""),
      public_enabled: .values.outputs.public_endpoint_enabled.value?
    }' <<<"${state_json}")"
clusters=$(jq -r .clusters <<<"${facts}"); k8s=$(jq -r .k8s <<<"${facts}")

if (( clusters == 0 || k8s == 0 )); then
  echo "no override needed in ${dir}: state has ${clusters} cluster(s) and ${k8s} helm/kubernetes/kubectl resource(s)"
  remove_ours; exit 0
fi
(( clusters == 1 )) || { echo "refusing: ${clusters} nebius_mk8s_v1_cluster resources in ${dir}; one root, one cluster" >&2; exit 1; }

public=$(jq -r .public <<<"${facts}"); private=$(jq -r .private <<<"${facts}"); ca=$(jq -r .ca <<<"${facts}")
public_enabled=$(jq -r .public_enabled <<<"${facts}")
case "${public_enabled}" in
  true) host="${public}"; kind=public ;;
  false) host="${private}"; kind=private ;;
  *) if [[ -n "${public}" ]]; then host="${public}"; kind=public; else host="${private}"; kind=private; fi ;;
esac
[[ -n "${host}" ]] || { echo "refusing: the cluster in ${dir} has no ${kind} endpoint in state; cannot pin the providers" >&2; exit 1; }
# Values go into HCL verbatim: allow only what a host and a PEM can contain (no quotes, no \${).
host_re='^[][A-Za-z0-9.:/_-]+$'
[[ "${host}" =~ ${host_re} ]] || { echo "refusing: unexpected characters in the ${kind} endpoint" >&2; exit 1; }
if ! grep -q -- '-----BEGIN CERTIFICATE-----' <<<"${ca}" || grep -q '[^A-Za-z0-9+/= -]' <<<"${ca}"; then
  echo "refusing: no PEM cluster_ca_certificate on the cluster in ${dir}" >&2; exit 1
fi

# Only override provider blocks the root declares (an override without a base block is an error).
declared() { cat "${dir}"/*.tf 2>/dev/null | grep -v '^#' | grep -q "^provider \"$1\""; }
# <<-EOT strips the common indent, so the PEM can sit indented under its attribute.
ca_block() { local pem="${ca%$'\n'}"; printf '<<-EOT\n%s  %s\n%sEOT' "$1" "${pem//$'\n'/$'\n'$1  }" "$1"; }

umask 077
tmp="$(mktemp "${dir}/.${name}.XXXXXX")"
trap 'rm -f "${tmp}"' EXIT
{
  echo "${marker}"
  echo "# In a destroy plan the cluster outputs are null and these providers would dial localhost; this"
  echo "# pins them to the ${kind} endpoint recorded in state (runbooks/teardown.md). Git-ignored (*_override.tf)."
  if declared helm; then
    if grep -q 'kubernetes = {' "${dir}"/providers.tf 2>/dev/null; then
      printf '\nprovider "helm" {\n  kubernetes = {\n    host                   = "%s"\n    cluster_ca_certificate = %s\n    token                  = var.iam_token\n  }\n}\n' "${host}" "$(ca_block '    ')"
    else
      printf '\nprovider "helm" {\n  kubernetes {\n    host                   = "%s"\n    cluster_ca_certificate = %s\n    token                  = var.iam_token\n  }\n}\n' "${host}" "$(ca_block '    ')"
    fi
  fi
  for p in kubernetes kubectl; do
    declared "${p}" || continue
    printf '\nprovider "%s" {\n  host                   = "%s"\n  cluster_ca_certificate = %s\n  token                  = var.iam_token\n}\n' "${p}" "${host}" "$(ca_block '  ')"
  done
} > "${tmp}"
chmod 600 "${tmp}"
mv "${tmp}" "${out}"
trap - EXIT
if git -C "${dir}" rev-parse --is-inside-work-tree >/dev/null 2>&1 && ! git -C "${dir}" check-ignore -q "${out}"; then
  rm -f "${out}"; echo "refusing: ${out} is not git-ignored (.gitignore must cover *_override.tf)" >&2; exit 1
fi
echo "wrote ${out} (${kind} endpoint ${host}; ${k8s} in-cluster resource(s) to refresh)"
[[ "${kind}" == private ]] && echo "note: the private endpoint is reachable only from inside the cluster's VPC (bastion or self-hosted runner); run the destroy plan from there" >&2
exit 0
